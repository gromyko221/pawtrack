/* ------------------------------------------------------------
   ЗАДАЧА 1. Год в подвале сам себя обновляет.

   Самая простая полезная программа: спросить у компьютера
   текущий год и вставить в страницу. 1 января ничего
   переписывать вручную не придётся.
   ------------------------------------------------------------ */

// document — это вся страница глазами JavaScript.
// querySelector находит ПЕРВЫЙ элемент по CSS-селектору.
// Селекторы те же, что в CSS: "#year" значит id="year".
const yearSlot = document.querySelector("#year");

// const — «постоянная», ящик со значением, который не будет заменён.
// Если бы значение менялось, писали бы let.

// if — условие. Проверяем, что элемент вообще нашёлся:
// если его на странице нет, querySelector вернёт null,
// и попытка что-то в него записать уронит скрипт.
// Такая проверка — привычка, которая экономит часы отладки.
if (yearSlot) {
  // new Date() — текущие дата и время. getFullYear() достаёт год.
  // textContent — текст внутри элемента. Присваиваем — текст меняется.
  yearSlot.textContent = new Date().getFullYear();
}


/* ------------------------------------------------------------
   ЗАДАЧА 2. Форма отправляется без ухода со страницы.

   Как было: нажал «Отправить» → браузер ушёл на сайт Formspree
   → человек увидел чужую английскую страницу «Thanks!» и потерял
   твой сайт. Половина посетителей после такого не возвращается.

   Как станет: данные уходят фоном, а на месте формы появляется
   твоё сообщение. Человек остаётся у тебя.
   ------------------------------------------------------------ */

const form = document.querySelector("#lead-form");
const status = document.querySelector("#form-status");

if (form) {

  // addEventListener — «слушай событие и выполняй функцию».
  // "submit" — событие отправки формы.
  // async перед функцией нужно, чтобы внутри работал await (см. ниже).
  form.addEventListener("submit", async function (event) {

    // По умолчанию браузер при submit перезагружает страницу
    // и уходит по адресу из action. preventDefault это отменяет:
    // «стой, я сам разберусь».
    event.preventDefault();

    const button = form.querySelector("button");

    // Блокируем кнопку, чтобы нетерпеливый посетитель
    // не отправил заявку пять раз подряд.
    button.disabled = true;
    button.textContent = "Отправляем…";

    // try / catch — «попробуй сделать, а если сломается, поймай ошибку».
    // Сеть может отвалиться в любой момент, и без catch человек
    // остался бы с надписью «Отправляем…» навсегда.
    try {

      // fetch — отправка запроса на сервер прямо из страницы.
      // FormData(form) собирает все поля формы по их атрибутам name.
      // await — «подожди ответа и только потом иди дальше».
      const response = await fetch(form.action, {
        method: "POST",
        body: new FormData(form),
        headers: { Accept: "application/json" }
        // Этот заголовок просит Formspree ответить данными,
        // а не HTML-страницей «Thanks!».
      });

      if (response.ok) {
        // Успех. Прячем форму и показываем благодарность.
        // classList.add("hidden") добавляет элементу класс,
        // а правило .hidden в style.css скрывает его.
        form.classList.add("hidden");
        status.className = "form-status ok";
        status.textContent =
          "Спасибо! Заявка получена. Ответим в течение двух дней.";
      } else {
        // Сервер ответил, но с ошибкой (например, форма отключена).
        throw new Error("Сервер вернул ошибку");
      }

    } catch (error) {
      // Сюда попадаем при обрыве сети или ошибке сервера.
      // Обязательно возвращаем кнопку в рабочее состояние
      // и даём запасной способ связи — иначе заявка потеряна.
      status.className = "form-status err";
      status.textContent =
        "Не получилось отправить. Попробуйте ещё раз или напишите нам на почту.";
      button.disabled = false;
      button.textContent = "Отправить заявку";
    }
  });
}


/* ============================================================
   ГЛАВНОЕ ИЗ ЭТОГО ФАЙЛА

   1. document.querySelector("...") — найти элемент на странице
   2. .textContent — прочитать или заменить текст элемента
   3. .classList.add("...") — навесить класс (а значит, стиль)
   4. addEventListener("событие", функция) — реагировать на действия
   5. if / else — принимать решения
   6. try / catch — переживать ошибки, не ломая страницу

   Этих шести штук хватает на 90% задач обычного сайта.

   ЧТО ПОПРОБОВАТЬ САМОЙ:
   • Поменяй текст благодарности на свой
   • Открой сайт, нажми F12 → вкладка Console, набери там
     document.querySelector("h1").textContent = "Привет!"
     и нажми Enter. Заголовок сайта изменится прямо на глазах.
     Это временно, до перезагрузки — но именно так и работает JS.
   ============================================================ */
